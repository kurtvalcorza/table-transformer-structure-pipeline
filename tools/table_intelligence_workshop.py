def stage(name, fresh=False):
    """Register a stage: restore the carried state, run, and persist it for the next stage."""
    def register(function):
        def run(args):
            if fresh:  # a new Run all starts from an empty state
                if state_file().is_file():
                    state_file().unlink()
                for name in STATE_NAMES:
                    globals().pop(name, None)
            restore_state()
            try:
                function(args)
            finally:
                persist_state()  # as in a kernel, what a failing stage changed before its error is kept
        STAGES[name] = run
        return function
    return register


